#!/usr/bin/env python
"""CLI to regenerate .github/state/known-notes-snapshot.json from the real running app.

Usage:
    uv run python scripts/export_notes_snapshot.py \\
        --base-url http://localhost:8000 --token dev-token-change-me

Calls GET /players/notes/active on the real running API and writes the response, plus a
generated-at timestamp, to .github/state/known-notes-snapshot.json -- committed to the repo so
.github/workflows/scout-watch.yml's dedup step (which cannot reach this app's database directly,
same constraint as every other standalone workflow in this repo -- see ARCHITECTURE.md's "FPL
Scout Watch" section) can read a recent snapshot of what's already known before proposing a
finding as new.

This file needs periodic manual refresh -- run this script again whenever new notes are created/
removed and you want the workflow's dedup check to reflect it (there is no automatic sync, same
as .github/state/current-squad.json).
"""

import argparse
import json
import sys
from datetime import UTC, datetime
from pathlib import Path

import httpx

_SNAPSHOT_PATH = Path(__file__).resolve().parents[1] / ".github" / "state" / "known-notes-snapshot.json"


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Regenerate the known-notes snapshot from the live API.")
    parser.add_argument("--base-url", default="http://localhost:8000", help="Base URL of the running API.")
    parser.add_argument("--token", required=True, help="APP_SHARED_TOKEN for the running API.")
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)

    response = httpx.get(
        f"{args.base_url}/players/notes/active",
        headers={"Authorization": f"Bearer {args.token}"},
        timeout=30.0,
    )
    response.raise_for_status()
    active_notes = response.json()

    snapshot = {
        "_comment": (
            "Generated by scripts/export_notes_snapshot.py from the real running app's "
            "GET /players/notes/active -- needs periodic manual refresh, there is no automatic "
            "sync. Consumed by .github/workflows/scout-watch.yml's dedup step."
        ),
        "generated_at": datetime.now(UTC).isoformat(),
        "active_notes": active_notes,
    }

    _SNAPSHOT_PATH.parent.mkdir(parents=True, exist_ok=True)
    _SNAPSHOT_PATH.write_text(json.dumps(snapshot, indent=2) + "\n")

    print(f"Wrote {len(active_notes)} active note(s) to {_SNAPSHOT_PATH}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
